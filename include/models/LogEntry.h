#pragma once

#include "util/TimeUtils.h"

#include <array>
#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <string_view>

namespace loganalyzer {

/// Severity levels, ordered from least to most severe.
/// The underlying values double as array indices (see toIndex), so they must
/// stay contiguous and start at zero.
enum class LogLevel : std::uint8_t {
    Trace = 0,
    Debug,
    Info,
    Warning,
    Error,
    Critical,
};

inline constexpr std::size_t kLogLevelCount = 6;

inline constexpr std::array<LogLevel, kLogLevelCount> kAllLogLevels{
    LogLevel::Trace, LogLevel::Debug, LogLevel::Info, LogLevel::Warning, LogLevel::Error, LogLevel::Critical,
};

[[nodiscard]] constexpr std::size_t toIndex(LogLevel level) noexcept {
    return static_cast<std::size_t>(level);
}

/// ERROR and CRITICAL count as errors for the error rate and "top errors".
[[nodiscard]] constexpr bool isErrorLevel(LogLevel level) noexcept {
    return level >= LogLevel::Error;
}

/// Canonical upper-case name, e.g. "WARNING".
[[nodiscard]] std::string_view toString(LogLevel level) noexcept;

/// Case-insensitive. Accepts the canonical names plus the common aliases
/// "WARN", "ERR", "FATAL" and "CRIT".
[[nodiscard]] std::optional<LogLevel> parseLogLevel(std::string_view text) noexcept;

struct LogEntryView;

/// One parsed log entry that owns its data.
///
/// Used wherever an entry must outlive the buffer it was read from: samples in
/// reports, test fixtures and the public API.
struct LogEntry {
    Timestamp timestamp{};
    LogLevel level = LogLevel::Info;
    std::string message;
    std::optional<std::string> sourceFile;   ///< e.g. "DatabasePool.cpp" (optional)
    std::optional<std::uint32_t> sourceLine; ///< line in that source file (optional)
    std::size_t lineNumber = 0;              ///< 1-based line in the log file; 0 = unknown

    [[nodiscard]] LogEntryView view() const noexcept;

    // C++20 defaulted comparison: member-wise ==, generated by the compiler.
    bool operator==(const LogEntry&) const = default;
};

/// Non-owning version of LogEntry. Its string_views point into the text the line
/// was parsed from, so it must not outlive that text.
///
/// Why it exists: the hot path parses, filters and counts millions of lines.
/// With views no line ever allocates memory just to be inspected; a LogEntry
/// (with its std::string copies) is created only for the few entries that are
/// kept as samples.
struct LogEntryView {
    Timestamp timestamp{};
    LogLevel level = LogLevel::Info;
    std::string_view message;
    std::string_view sourceFile;  ///< empty when the line had no source location
    std::uint32_t sourceLine = 0; ///< meaningful only if sourceFile is non-empty
    std::size_t lineNumber = 0;

    [[nodiscard]] bool hasSourceLocation() const noexcept { return !sourceFile.empty(); }

    /// Deep-copies the viewed text into an owning LogEntry.
    [[nodiscard]] LogEntry toEntry() const;
};

inline LogEntryView LogEntry::view() const noexcept {
    LogEntryView v;
    v.timestamp = timestamp;
    v.level = level;
    v.message = message;
    if (sourceFile) {
        v.sourceFile = *sourceFile;
        v.sourceLine = sourceLine.value_or(0);
    }
    v.lineNumber = lineNumber;
    return v;
}

inline LogEntry LogEntryView::toEntry() const {
    LogEntry entry;
    entry.timestamp = timestamp;
    entry.level = level;
    entry.message = std::string(message);
    if (hasSourceLocation()) {
        entry.sourceFile = std::string(sourceFile);
        entry.sourceLine = sourceLine;
    }
    entry.lineNumber = lineNumber;
    return entry;
}

} // namespace loganalyzer
